def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Install or check way-too-good skills for agent harnesses.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    install = sub.add_parser("install", help="copy canonical skills into harness directories")
    install.add_argument("--scope", choices=("user", "project"), default="user")
    install.add_argument(
        "--dest",
        type=Path,
        help="where files are written (default: your home, or this repo with --scope project). Detection still uses your real home",
    )
    install.add_argument("--provider", help="comma-separated provider ids (see --list)")
    install.add_argument("--all", action="store_true", help="every supported harness")
    install.add_argument("--with-instructions", action="store_true", help="write pointer files only if they do not already exist")
    install.add_argument("--dry-run", action="store_true")
    install.add_argument("--list", action="store_true", help="show paths and write nothing")
    sub.add_parser("check", help="validate skills, pointers, and the installer")
    sub.add_parser("update", help="rewrite generated/ and the README compatibility table")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.cmd == "check":
            return run_check()
        if args.cmd == "update":
            return run_update()
        if args.cmd != "install":
            parser.error(f"unknown command {args.cmd}")
            return 2
        providers = load_providers()
        if args.list:
            sys.stdout.write(list_providers(providers))
            return 0
        if args.all and args.provider:
            raise InstallError("Pass either --all or --provider, not both.")
        skills = load_skills()
        explicit = parse_provider_arg(args.provider, providers) if args.provider else None
        code, text = perform_install(
            providers,
            skills,
            args.scope,
            args.dest,
            explicit,
            args.all,
            args.dry_run,
            args.with_instructions,
        )
        sys.stdout.write(text)
        return code
    except (SkillCheckError, InstallError) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
